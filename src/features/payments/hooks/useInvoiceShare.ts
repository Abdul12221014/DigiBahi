/**
 * useInvoiceShare — v2
 * ─────────────────────
 * Central hook for all WhatsApp invoice sharing.
 * Uses the 3-level fallback chain (Web Share → wa.me → PDF download).
 * Integrates analytics tracking on every event.
 *
 * Used by: EntryForm, LedgerTable
 */

import { useState } from 'react';
import { toast } from 'sonner';
import { db, LedgerEntry } from '@/lib/db';
import { formatCurrency, formatDate } from '@/lib/gst';
import { analytics } from '@/lib/analytics';
import { shareWithFallback, ShareMethod } from '@/lib/shareRetry';
import { getDefaultCountry } from '@/lib/countryCode';

// Lazy-load jsPDF to keep initial bundle lean
const loadJsPDF = async () => {
  const { default: jsPDF } = await import(/* webpackChunkName: "jspdf" */ 'jspdf');
  return jsPDF;
};

// ─── PDF Label per share method ───────────────────────────────────────────────
const METHOD_LABELS: Record<ShareMethod, string> = {
  web_share:    'Preparing to share…',
  wa_me:        'Opening WhatsApp…',
  pdf_download: 'Downloading invoice PDF…',
};

// ─── PDF Generator ────────────────────────────────────────────────────────────

async function generatePDFForEntry(
  entry: LedgerEntry,
  customerPhone: string,
): Promise<Blob> {
  const jsPDF    = await loadJsPDF();
  const doc      = new jsPDF();
  const pageW    = doc.internal.pageSize.getWidth();
  const margin   = 20;
  let   yPos     = margin;

  // Company details from DB
  const company = await db.companySettings.toCollection().last();

  // Header
  doc.setFontSize(18);
  doc.setTextColor(42, 103, 178);
  doc.text(company?.businessName || 'DigitalMuneem', pageW / 2, yPos, { align: 'center' });
  yPos += 8;

  if (company?.address) {
    doc.setFontSize(10);
    doc.setTextColor(0, 0, 0);
    doc.text(company.address, pageW / 2, yPos, { align: 'center' });
    yPos += 5;
  }
  if (company?.gstin) {
    doc.setFontSize(9);
    doc.text(`GSTIN: ${company.gstin}`, pageW / 2, yPos, { align: 'center' });
    yPos += 5;
  }
  yPos += 5;

  // Invoice title
  const title = entry.type === 'receipt' ? 'RECEIPT' : 'TAX INVOICE';
  doc.setFontSize(16);
  doc.setTextColor(0, 0, 0);
  doc.text(title, margin, yPos);
  yPos += 10;

  // Invoice meta
  const displayId = entry.reference_no || entry.id?.toString() || 'Draft';
  doc.setFontSize(10);
  doc.text(`${title} No: ${displayId}`, margin, yPos);
  doc.text(`Date: ${formatDate(entry.date)}`, pageW - margin, yPos, { align: 'right' });
  yPos += 8;

  // Bill-to
  doc.setFontSize(11);
  doc.setFont(undefined, 'bold');
  doc.text('Bill To:', margin, yPos);
  yPos += 6;
  doc.setFont(undefined, 'normal');
  doc.text(entry.party_name || 'Cash Customer', margin, yPos);
  yPos += 5;
  if (customerPhone) {
    doc.text(`Phone: ${customerPhone}`, margin, yPos);
  }
  yPos += 10;

  // Line items
  doc.setFont(undefined, 'bold');
  doc.setFontSize(10);
  doc.text('Description', margin, yPos);
  doc.text('Amount', pageW - margin, yPos, { align: 'right' });
  yPos += 6;
  doc.setDrawColor(200, 200, 200);
  doc.line(margin, yPos, pageW - margin, yPos);
  yPos += 5;

  doc.setFont(undefined, 'normal');
  doc.text(entry.description || 'Invoice Items', margin, yPos);
  doc.text(formatCurrency(entry.amount), pageW - margin, yPos, { align: 'right' });
  yPos += 8;

  // Totals
  const totalsX = pageW - margin - 60;
  doc.setFontSize(9);
  doc.text('Subtotal:', totalsX, yPos);
  doc.text(formatCurrency(entry.amount), pageW - margin, yPos, { align: 'right' });
  yPos += 5;

  if (entry.gstRate && entry.gstAmount) {
    doc.text(`GST (${entry.gstRate}%):`, totalsX, yPos);
    doc.text(formatCurrency(entry.gstAmount), pageW - margin, yPos, { align: 'right' });
    yPos += 6;
  }

  doc.setDrawColor(0, 0, 0);
  doc.line(totalsX, yPos, pageW - margin, yPos);
  yPos += 6;

  const totalAmount = entry.amount + (entry.gstAmount || 0);
  doc.setFont(undefined, 'bold');
  doc.setFontSize(11);
  doc.text('Total Amount:', totalsX, yPos);
  doc.text(formatCurrency(totalAmount), pageW - margin, yPos, { align: 'right' });
  yPos += 10;

  // Footer
  doc.setFont(undefined, 'normal');
  doc.setFontSize(8);
  doc.setTextColor(128, 128, 128);
  doc.text(
    'Generated by DigitalMuneem Accounting Solutions',
    pageW / 2,
    doc.internal.pageSize.getHeight() - 10,
    { align: 'center' },
  );

  return doc.output('blob');
}

// ─── Hook ─────────────────────────────────────────────────────────────────────

export type ShareStatus = 'idle' | 'generating' | 'sharing' | 'done' | 'error';

export function useInvoiceShare() {
  const [isSharing, setIsSharing]     = useState(false);
  const [shareStatus, setShareStatus] = useState<ShareStatus>('idle');
  const [shareMethod, setShareMethod] = useState<ShareMethod | null>(null);

  const shareInvoice = async (entry: LedgerEntry, customerPhone: string) => {
    const country = getDefaultCountry();

    analytics.track('invoice_share_clicked', {
      entry_type:  entry.type,
      has_party:   !!entry.party_name,
      amount:      entry.amount,
      gst_rate:    entry.gstRate,
    });

    setIsSharing(true);
    setShareStatus('generating');

    // "Preparing…" toast that dismisses automatically
    const loadingToastId = toast.loading('Preparing your invoice PDF…');

    try {
      // 1. Generate PDF
      const pdfBlob = await generatePDFForEntry(entry, customerPhone);
      toast.dismiss(loadingToastId);

      // 2. Build share content
      const totalAmount = entry.amount + (entry.gstAmount || 0);
      const displayId   = entry.reference_no || entry.id?.toString() || 'Draft';
      const message     =
        `Hello ${entry.party_name || 'Customer'},\n` +
        `Here is your bill (No: ${displayId}) of ${formatCurrency(totalAmount)}.\n` +
        `Date: ${formatDate(entry.date)}\n` +
        `Thank you for your business!`;
      const filename = `Invoice_${displayId}.pdf`;

      // 3. Attempt share with fallback chain
      setShareStatus('sharing');
      const result = await shareWithFallback(
        {
          pdfBlob,
          filename,
          message,
          phone:    customerPhone,
          dialCode: country.dialCode,
          title:    `Invoice ${displayId}`,
        },
        (method) => {
          setShareMethod(method);
          // Update toast to reflect current method
          toast.loading(METHOD_LABELS[method], { id: 'share-progress' });
        },
      );

      toast.dismiss('share-progress');
      setShareStatus('done');

      // Success feedback by method
      if (result.method === 'pdf_download') {
        toast.info(
          'PDF downloaded. Open WhatsApp and attach the file manually.',
          { duration: 6000 },
        );
      } else {
        toast.success('Invoice shared successfully!');
      }

    } catch (err: unknown) {
      toast.dismiss(loadingToastId);
      toast.dismiss('share-progress');

      // User manually cancelled — silent
      if (err instanceof Error && err.name === 'AbortError') {
        setShareStatus('idle');
        return;
      }

      setShareStatus('error');
      analytics.track('invoice_share_failed', {
        error:       err instanceof Error ? err.message : String(err),
        entry_type:  entry.type,
      });

      // Retry button in toast
      toast.error('Failed to share invoice.', {
        duration: 10_000,
        action: {
          label: 'Retry',
          onClick: () => shareInvoice(entry, customerPhone),
        },
      });
    } finally {
      setIsSharing(false);
    }
  };

  return { shareInvoice, isSharing, shareStatus, shareMethod };
}
